# Build i18n/zt.js: a small simplified→traditional table covering only the game's own text.
# Character map + phrase fixes (where OpenCC's phrase conversion differs from char-by-char).
# usage: python3 build_zt.py <game dir>
import sys, re, json, glob, difflib, opencc
G = sys.argv[1]
_cc = opencc.OpenCC('s2tw')
# game vocabulary: Taiwan/HK UI words, and game terms OpenCC gets wrong (回復 = heal, 冷面 = stern face)
OVR = {'回复':'回復','冷面':'冷面','几率':'機率','登录':'登入','设置':'設定','网络':'網路','屏幕':'螢幕','默认':'預設',
       '保存':'儲存','加载':'載入','设备':'裝置','信息':'資訊','链接':'連結','视频':'影片','鼠标':'滑鼠','金钟':'金鐘','钟声':'鐘聲','只有':'只有'}
_ovr = re.compile('|'.join(sorted(OVR, key=len, reverse=True)))
class _CC:
    def convert(self, s):
        out, last = '', 0
        for m in _ovr.finditer(s):
            out += _cc.convert(s[last:m.start()]) + OVR[m.group(0)]; last = m.end()
        return out + _cc.convert(s[last:])
cc = _CC()
han = re.compile(r'[㐀-鿿]')
texts = set()
for f in glob.glob(G + '/js/*.js') + [G + '/index.html', G + '/css/style.css']:
    s = open(f, encoding='utf8').read()
    # every run of text containing Chinese, split on code-ish delimiters
    for m in re.finditer(r"[^'\"`<>{}$\n]*[㐀-鿿][^'\"`<>{}$\n]*", s):
        texts.add(m.group(0))
texts = sorted(texts)
chars = sorted({ch for t in texts for ch in t if han.match(ch)})
cmap = {}
for ch in chars:
    t = cc.convert(ch)
    if len(t) == 1 and t != ch: cmap[ch] = t
def run(s, phrases):
    o, i = '', 0
    while i < len(s):
        hit = None
        for a, b in phrases.get(s[i], []):
            if s.startswith(a, i): hit = (a, b); break
        if hit: o += hit[1]; i += len(hit[0]); continue
        o += cmap.get(s[i], s[i]); i += 1
    return o
phrases = {}
def add(a, b):
    L = phrases.setdefault(a[0], [])
    if (a, b) not in L: L.append((a, b)); L.sort(key=lambda x: -len(x[0]))
for k, v in OVR.items():
    if k != v: add(k, v)
for it in range(6):
    bad = 0
    for s in texts:
        want = cc.convert(s); got = run(s, phrases)
        if got == want: continue
        bad += 1
        sm = difflib.SequenceMatcher(None, got, want, autojunk=False)
        if len(got) != len(s) or it >= 2:  # length drift or stubborn: take the whole text
            add(s, want); continue
        for op, i1, i2, j1, j2 in sm.get_opcodes():
            if op == 'equal': continue
            a0, a1 = max(0, i1 - 1), min(len(s), i2 + 1)
            b0, b1 = j1 - (i1 - a0), j2 + (a1 - i2)
            if b0 < 0 or b1 > len(want): add(s, want); break
            add(s[a0:a1], want[b0:b1])
    print('iteration', it, 'mismatches', bad, file=sys.stderr)
    if not bad: break
data = {'c': cmap, 'p': {k: [list(x) for x in v] for k, v in phrases.items()}}
open(G + '/i18n/zt.js', 'w', encoding='utf8').write(
    "/* 繁體中文: generated by tools/build_zt.py from OpenCC s2tw + game vocabulary over the game's own text */\nI18N_LOAD('zt'," +
    json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ');\n')
print('chars', len(cmap), 'phrases', sum(len(v) for v in phrases.values()), file=sys.stderr)
for k, v in list(phrases.items())[:60]: print(v, file=sys.stderr)
