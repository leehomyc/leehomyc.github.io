def has_final(ch):
    o = ord(ch) - 0xAC00
    return 0 <= o < 11172 and o % 28 != 0
PART = [('을','를'),('이','가'),('은','는'),('과','와'),('으로','로'),('이(가)','이(가)')]
def ko_fix(text, old, new):
    def rep(m):
        p = m.group(1) or ''
        last = new[-1]; fin = has_final(last); rieul = (ord(last) - 0xAC00) % 28 == 8 if has_final(last) else False
        for a, b in PART:
            if p in (a, b):
                if a == '으로': p = '로' if (not fin or rieul) else '으로'
                elif a != b: p = a if fin else b
                break
        return new + p
    return re.sub(re.escape(old) + r'(이\(가\)|으로|을|를|이|가|은|는|과|와)?', rep, text)
