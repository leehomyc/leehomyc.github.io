def apply(loc, v):
    if loc == 'ja':
        for a, b in JA: v = v.replace(a, b)
    else:
        for a, b in KO:
            if a in v: v = ko_fix(v, a, b)
        for a, b in KO_TONE: v = v.replace(a, b)
    return v
